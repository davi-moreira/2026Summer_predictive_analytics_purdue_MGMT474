# ============================================================= 5. SINGLE LAYER NN
md(r"""# 5. Single Layer Neural Network (the math)

You just trained a multi-layer network. Here is the math of the simplest version — a single hidden layer — which is the building block for everything else. A single-layer network with $K$ hidden units computes:

$$
\begin{align*}
f(X) &= \beta_0 + \sum_{k=1}^{K} \beta_k h_k(X) \\
     &= \beta_0 + \sum_{k=1}^{K} \beta_k\, g\!\left(w_{k0} + \sum_{j=1}^{p} w_{kj} X_j \right).
\end{align*}
$$""")

md(img("10_1-1.png", 560, "Single layer neural network diagram",
       "Network diagram of a single-layer neural network."))

md(r"""**Reading the diagram.** Neural networks are often drawn as **network diagrams**:

- **Input layer (orange circles):** $X_1, X_2, X_3, X_4$ — observed features from the dataset.
- **Hidden layer (blue circles):** $A_1, \ldots, A_5$ — transformations (activations) computed from the inputs.
- **Output layer (pink circle):** $f(X) \to Y$ — also observed (a label or continuous response).

**Observed vs. latent.** The $X_j$ are observed (inputs) and $Y$ is observed (the response). The **hidden units** $A_k$ are **not** observed — they are learned transformations.

**The hidden layer as transformations.** Each activation is

$$
A_k = h_k(X) = g\!\Bigl(w_{k0} + \sum_{j=1}^{p} w_{kj} X_j\Bigr),
$$

where $g(\cdot)$ is a non-linear function (ReLU, sigmoid, tanh) and the $w_{kj}$ are weights learned during training. Each hidden unit has a *different* set of weights, hence a different transformation. The network learns all the weights $w_{kj}, w_{k0}, \beta_k, \beta_0$ during training — exactly the `optimizer.step()` updates you watched run in Section 4.""")

md(r"""## Single Layer Neural Network: Details""")
md(img("10_2-1.png", 620, "Activation function details"))
md(r"""- $A_k = h_k(X) = g\!\left(w_{k0} + \sum_{j=1}^{p} w_{kj} X_j\right)$ are the **activations** in the *hidden layer* — a non-linear transformation of a linear function.
- $g(z)$ is the **activation function**. Two popular choices: the **sigmoid** and the **rectified linear unit (ReLU)** — the `nn.ReLU()` from your lab.
- Activation functions in hidden layers are typically non-linear; otherwise the whole model collapses to a linear model.
- For regression, the model is fit by minimizing $\sum_{i=1}^{n} (y_i - f(x_i))^2$.""")

md(r"""## NN Example: MNIST Digits""")
md(img("10_3a-1.png", 360, "MNIST digit examples"))
md(img("10_3b-1.png", 420, "MNIST two-layer network"))
md(r"""- **Handwritten digits:** 28×28 grayscale images, 60K train / 10K test — the same shape as the FashionMNIST images you just classified. Features are the 784 pixel values $\in (0, 255)$; labels are the digit class $0\text{–}9$.
- A two-layer network with **256 units** at the first layer, **128 units** at the second, and **10 units** at the output has — along with the biases — **235,146 parameters**.

> **A question that often comes up here:** *"235,146 parameters for a tiny image — isn't that wildly overfit?"* It would be for a noisy tabular problem with a few thousand rows. But image recognition has a very **high signal-to-noise ratio** and a huge training set, so the network has enough data to pin those parameters down. This is the same theme you will see again under "double descent" — over-parameterization is far less dangerous when the signal is strong and the data is large.""")

# ============================================================= 6. FITTING NN
md(r"""# 6. Fitting Neural Networks

You watched the intuition for this in Section 3 (Chapters 2–4) and ran it in Section 4's train loop. Here is the formal version.

We fit the network by minimizing squared error:

$$
\min_{\{w_k\}_{1}^K,\, \beta}\; \frac{1}{2} \sum_{i=1}^n \bigl(y_i - f(x_i)\bigr)^2,
\qquad
f(x_i) = \beta_0 + \sum_{k=1}^K \beta_k\, g\!\left(w_{k0} + \sum_{j=1}^p w_{kj} x_{ij}\right).
$$

This problem is hard because the objective is **non-convex**. Despite that, effective algorithms optimize complex networks efficiently.

## Non-convex functions and gradient descent

Let $R(\theta) = \frac{1}{2}\sum_{i=1}^n (y_i - f_\theta(x_i))^2$ with $\theta = (\{w_k\}_{1}^K, \beta)$.""")
md(img("10_17-1.png", 560, "Gradient descent on a non-convex surface"))
md(r"""We compute the **gradient vector** $\nabla R(\theta^t)$ (the partial derivatives at the current guess), which points *uphill*, and step the other way:

$$
\theta^{t+1} \gets \theta^t - \rho\, \nabla R(\theta^t),
$$

where $\rho$ is the **learning rate** (your `lr=1e-3`). If we had started elsewhere, we might descend into a **local** rather than the global minimum — hard to tell apart in high dimensions.""")

md(r"""## Gradients and backpropagation

Because $R(\theta) = \sum_{i=1}^n R_i(\theta)$ is a sum, its gradient is the sum of gradients. With $z_{ik} = w_{k0} + \sum_{j=1}^p w_{kj} x_{ij}$, backpropagation applies the **chain rule**:

$$
\frac{\partial R_i(\theta)}{\partial \beta_k}
= -(y_i - f_\theta(x_i)) \cdot g(z_{ik}),
\qquad
\frac{\partial R_i(\theta)}{\partial w_{kj}}
= -(y_i - f_\theta(x_i)) \cdot \beta_k \cdot g'(z_{ik}) \cdot x_{ij}.
$$

This is exactly the calculation `loss.backward()` ran for you in Section 4.

## Tricks of the trade

- **Stochastic gradient descent (SGD).** Rather than use *all* the data each step, use a small **mini-batch** drawn at random — your `batch_size=64`.
- **Epoch.** One epoch is the number of mini-batch updates needed to process $n$ samples once — for FashionMNIST, $60{,}000/64 \approx 938$ updates per epoch.
- **Regularization.** Ridge and lasso shrink the weights; two other popular forms are **dropout** and **augmentation**, next.""")

md(r"""## Dropout learning""")
md(img("10_1_4-1.png", 560, "Dropout"))
md(r"""- At each SGD update, randomly **remove** units with probability $\phi$, and scale up the weights of those retained by $1/(1-\phi)$ to compensate.
- In simple cases this is equivalent to **ridge** regularization; the other units *stand in* for those temporarily removed.
- Similar in spirit to randomly omitting variables when growing trees in random forests.

## Ridge and data augmentation""")
md(img("10_1_5-1.png", 560, "Data augmentation as ridge"))
md(r"""- Make many copies of each $(x_i, y_i)$ and add a small amount of Gaussian noise to the $x_i$ — a little cloud around each observation — but leave the $y_i$ alone.
- This makes the fit robust to small perturbations in $x_i$, and is equivalent to ridge regularization in an OLS setting.

## Data augmentation on the fly""")
md(img("10_1_6-1.png", 560, "Image data augmentation"))
md(r"""- Especially effective with SGD for images: natural transformations are applied to each training image as it is sampled, creating a cloud of images around each original.
- The label is left unchanged — in each case still **tiger**. Improves CNN performance and is similar to ridge.""")

md(r"""## Double descent""")
md(r"""- With neural networks, it seems better to have **too many** hidden units than too few — and more hidden layers better than few.
- Running SGD until *zero* training error often gives good out-of-sample error; adding even more units sometimes gives **even better** out-of-sample error.
- What happened to overfitting and the usual bias-variance trade-off?""")
md(img("10_20-1.png", 560, "The double-descent error curve"))
md(r"""**The double-descent error curve.** When $d \le 20$ the model is OLS and we see the usual bias-variance trade-off. When $d > 20$ we revert to the minimum-norm solution; as $d$ increases above 20, $\sum_{j=1}^d \hat\beta_j^2$ **decreases**, giving less wiggly solutions.""")
md(img("10_21-1.png", 560, "Less wiggly solutions for larger d"))
md(r"""By analogy, deep and wide networks fit by SGD down to zero training error often generalize well — *especially* in high signal-to-noise problems like image recognition, where the zero-error solution is mostly signal.""")

