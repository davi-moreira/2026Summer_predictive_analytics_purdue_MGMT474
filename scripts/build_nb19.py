print("input batch:", input_image.size())

flatten = nn.Flatten()
flat_image = flatten(input_image)
print("after Flatten:", flat_image.size())          # 3 x 784

layer1 = nn.Linear(in_features=28*28, out_features=20)
hidden1 = layer1(flat_image)
print("after Linear(784->20):", hidden1.size())     # 3 x 20

print("\nBefore ReLU (first row):\n", hidden1[0])
