md(r"""We define the network by subclassing `nn.Module`: the layers go in `__init__`, and `forward` says how data flows through them. This is a **multi-layer perceptron** — flatten the 28×28 image into 784 numbers, then three fully-connected (`Linear`) layers with **ReLU** activations between them, ending in **10 logits** (one score per class).

- `nn.Flatten()` turns the 2D image (28×28) into a 1D vector of 784 values.
- `nn.Linear(28*28, 512)` projects those 784 values into 512 learned features (`output = x · W + b`).
- `nn.ReLU()` keeps positives, zeroes negatives — the non-linearity that lets the network learn complex patterns.
- The final `nn.Linear(512, 10)` outputs the 10 class logits.""")
code(r"""class NeuralNetwork(nn.Module):
    def __init__(self):
        super().__init__()
        self.flatten = nn.Flatten()
        self.linear_relu_stack = nn.Sequential(
            nn.Linear(28*28, 512),
            nn.ReLU(),
            nn.Linear(512, 512),
            nn.ReLU(),
            nn.Linear(512, 10),
        )

    def forward(self, x):
        x = self.flatten(x)
        logits = self.linear_relu_stack(x)
        return logits

model = NeuralNetwork().to(device)
print(model)""")

md(r"""### Inside the model, layer by layer

To see what each layer does to the data, push a sample mini-batch of **3 images** through the pieces one at a time and watch the shapes change.""")
