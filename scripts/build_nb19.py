# ============================================================= 9. RNN
md(r"""# 9. Recurrent Neural Networks — RNN

Often data arrive as **sequences**: documents (words in order), time series, recorded speech or music. RNNs take this sequential nature into account and build a **memory** of the past. The feature for each observation is a **sequence** of vectors $X = \{X_1, X_2, \ldots, X_L\}$; the target $Y$ is often a single variable (e.g. *Sentiment*) but can also be a sequence.

## Simple RNN architecture""")
md(img("10_12-1.png", 560, "Simple RNN architecture"))
md(r"""- The hidden layer is a sequence of vectors $A_\ell$, each receiving input $X_\ell$ and the previous hidden state $A_{\ell-1}$, and producing an output $O_\ell$.
- The **same** weights $\mathbf{W}, \mathbf{U}, \mathbf{B}$ are used at every step — hence **recurrent**.

## RNN in detail

With $X_\ell = (X_{\ell 1}, \ldots, X_{\ell p})$ and $A_\ell = (A_{\ell 1}, \ldots, A_{\ell K})$, the $k$-th hidden component is

$$
A_{\ell k} = g\!\left(w_{k0} + \sum_{j=1}^{p} w_{kj} X_{\ell j} + \sum_{s=1}^{K} u_{ks} A_{\ell-1,s}\right),
\qquad
O_\ell = \beta_0 + \sum_{k=1}^{K} \beta_k A_{\ell k}.
$$

**Three variants you will hear named:**

- **Vanilla RNN** — the original; trains poorly on long sequences (gradients vanish).
- **LSTM** (Long Short-Term Memory) — adds gates that learn what to remember and forget. The default for sequence problems from \~2014 to \~2018.
- **Transformer** — replaces recurrence with attention, processes the whole sequence in parallel, and now dominates language and increasingly time series. ChatGPT, Claude, and every modern LLM are transformers.""")

md(r"""# 10. RNN for Document Classification

- A document is a sequence of words $\{\mathcal{W}_\ell\}_{1}^{L}$, truncated/padded to a common length $L$ (here $L = 500$).
- Each word is a **one-hot** binary vector of length 10K — extremely sparse, and it would not work well directly.
- Instead we use a lower-dimensional pretrained **word embedding** matrix $\mathbf{E}$, reducing each length-10K binary vector to a real vector of dimension $m \ll 10\text{K}$.""")
